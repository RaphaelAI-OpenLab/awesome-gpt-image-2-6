"""Regression coverage for source cases and generated repository routes."""
import copy
import hashlib
import tempfile
import re
import sys
import unittest
from pathlib import Path
from unittest.mock import patch
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'scripts'))
from common import GENERATED_MARKER, ROOT, load_data, read_json, repo_url
from source_cases import read_cases, visible, page_path, render_detail, preview
from build_readme import outputs, render_readme, stale_case_pages
from validate import validate, validate_source_cases, schema_errors


class CollectionTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.config, cls.prompts = load_data()
        cls.cases = read_cases()

    def errors_for(self, item):
        errors = []
        validate_source_cases(self.config, [item], [], errors)
        return errors

    def test_current_data_and_local_links(self):
        self.assertEqual(validate()[0], [])

    def test_generated_files_match(self):
        expected = outputs(self.config, self.prompts)
        self.assertEqual(stale_case_pages(expected), [])
        for path, text in expected.items():
            self.assertEqual(path.read_text(), text, str(path))
        self.assertEqual(outputs(self.config, self.prompts), expected)

    def test_stale_pages_recognize_legacy_and_current_generation_markers(self):
        legacy = "<!-- Generated by scripts/build_readme.py. Edit site.config.json, content/prompts.json and content/source-cases.json. -->"
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            expected, stale = {}, set()
            for name, marker in (("legacy", legacy), ("current", GENERATED_MARKER)):
                for state in ("removed", "retained"):
                    path = root / "cases" / f"{name}-{state}" / "README.md"
                    path.parent.mkdir(parents=True)
                    path.write_text(marker + "\n\nGenerated case.\n", encoding="utf-8")
                    if state == "retained":
                        expected[path] = path.read_text(encoding="utf-8")
                    else:
                        stale.add(path)
            manual = root / "cases" / "manual" / "README.md"
            manual.parent.mkdir(parents=True)
            manual.write_text("# Manually maintained case\n", encoding="utf-8")
            with patch("build_readme.ROOT", root):
                self.assertEqual(set(stale_case_pages(expected)), stale)

    def test_every_visible_case_has_bilingual_internal_routes(self):
        generated = outputs(self.config, self.prompts)
        for lang in ('en', 'zh-CN'):
            readme = render_readme(self.config, self.prompts, lang)
            for case in visible(self.cases):
                route = page_path(case, lang)
                self.assertIn(route, readme)
                self.assertIn(ROOT / route, generated)
                self.assertIn(case['source']['url'], generated[ROOT / route])

    def test_displayed_images_are_local(self):
        for path, text in outputs(self.config, self.prompts).items():
            sources = re.findall(r'<img[^>]+src="([^"]+)"', text)
            sources += re.findall(r'!\[[^]]*\]\(([^)]+)\)', text)
            for source in sources:
                self.assertNotRegex(source, r'^(?:https?:|//)')
                self.assertTrue((path.parent / source).is_file(), source)

    def test_unknown_prompt_has_no_fake_prompt(self):
        item = copy.deepcopy(self.cases[0])
        item['prompt'] = {'status': 'not-public', 'url': None}
        for lang in ('en', 'zh-CN'):
            text = render_detail(item, lang)
            self.assertIn('PLACEHOLDER' if lang == 'en' else '占位', text)
            self.assertNotIn('```', text)

    def test_drafts_are_not_rendered(self):
        cases = copy.deepcopy(self.cases)
        cases[0]['status'] = 'draft'
        with patch('source_cases.read_cases', return_value=cases), patch('homepage.read_cases', return_value=cases):
            generated = outputs(self.config, self.prompts)
            self.assertNotIn(ROOT / page_path(cases[0], 'en'), generated)
            self.assertNotIn(page_path(cases[0], 'en'), render_readme(self.config, self.prompts, 'en'))

    def test_duplicate_ids_are_rejected(self):
        errors=[]
        validate_source_cases(self.config,[self.cases[0],self.cases[0]],[],errors)
        self.assertTrue(any('duplicate' in x for x in errors))

    def test_cross_dataset_collision_is_rejected(self):
        errors=[]
        validate_source_cases(self.config,[self.cases[0]],[{'id':self.cases[0]['id']}],errors)
        self.assertTrue(any('duplicate' in x for x in errors))

    def test_ambiguous_variant_is_rejected(self):
        item=copy.deepcopy(self.cases[0]);item['model']['variants']=['unspecified','sunburst']
        self.assertTrue(self.errors_for(item))

    def test_missing_bilingual_evidence_is_rejected(self):
        item=copy.deepcopy(self.cases[0]);item['model']['evidence']['zh-CN']=''
        self.assertTrue(self.errors_for(item))

    def test_schema_rejects_unknown_fields(self):
        item=copy.deepcopy(self.cases[0]);item['fake_prompt']='invented'
        schema=read_json('content/source-cases.schema.json')
        self.assertTrue(schema_errors([item],schema,'cases',schema))

    def test_public_prompt_requires_source(self):
        item=copy.deepcopy(self.cases[0]);item['prompt']['url']=None
        self.assertTrue(self.errors_for(item))

    def test_copyright_notice_uses_this_repository_issue_route(self):
        for lang in ('en', 'zh-CN'):
            text=render_readme(self.config,self.prompts,lang)
            self.assertIn('Copyright notice' if lang == 'en' else '版权声明', text)
            self.assertIn(repo_url(self.config) + '/issues/new', text)
            self.assertIn('remove it immediately' if lang == 'en' else '我们将立即移除', text)

    def test_local_media_integrity_is_checked(self):
        item=self.media_item()
        item['media'][0]['sha256']='0'*64
        self.assertTrue(any('checksum' in x for x in self.errors_for(item)))
        item=self.media_item();item['media'][0]['bytes']=0
        self.assertTrue(any('file size' in x for x in self.errors_for(item)))
        item=self.media_item();item['media'][0]['mime_type']='video/mp4'
        self.assertTrue(any('actual file format' in x for x in self.errors_for(item)))

    def test_source_attributed_does_not_require_official_creator(self):
        item=self.media_item();item['source']['type']='community'
        self.assertEqual(self.errors_for(item), [])
        item['media'][0]['rights']['evidence_url']='https://example.com/unrelated'
        self.assertTrue(any('exact original source' in x for x in self.errors_for(item)))

    def test_reference_media_is_not_a_featured_output(self):
        item=self.media_item()
        for media in item['media']: media['role']='reference'
        self.assertIsNone(preview(item))
        self.assertIn('Reference/input image', render_detail(item, 'en'))

    def test_local_mp4_is_a_video_link_not_an_image(self):
        item=self.media_item();item['media']=item['media'][:1];m=item['media'][0]
        data=b'\x00\x00\x00\x18ftypmp42'+b'\x00'*12
        m.update(path=f"assets/examples/{item['id']}/clip.mp4",source_url='https://example.com/clip.mp4',kind='video',role='output',bytes=len(data),sha256=hashlib.sha256(data).hexdigest(),mime_type='video/mp4')
        with tempfile.TemporaryDirectory() as directory:
            path=Path(directory)/m['path'];path.parent.mkdir(parents=True);path.write_bytes(data)
            with patch('validate.ROOT', Path(directory)):
                self.assertEqual(self.errors_for(item), [])
        text=render_detail(item,'en')
        self.assertIn('[Open local video file]',text)
        self.assertNotRegex(text,r'!\[[^]]*\]\([^)]*clip.mp4')
        self.assertIsNone(preview(item))

    def test_access_notes_distinguish_original_page_and_media(self):
        item=copy.deepcopy(next(x for x in self.cases if x.get('access',{}).get('page_status')=='blocked'))
        self.assertEqual(item['access']['media_status'],'unknown')
        text=render_detail(item,'en')
        self.assertIn('Original page:',text)
        self.assertIn('Media:',text)
        self.assertIn('No direct-media request was made',text)
        self.assertIn('../../docs/MEDIA_ACCESS_2026-11-05.md',text)

    def test_archived_access_status_requires_all_files(self):
        item=copy.deepcopy(next(x for x in self.cases if x.get('access',{}).get('media_status')=='archived'))
        item['media'][0]['path']=None
        self.assertTrue(any('archived requires all recorded media' in x for x in self.errors_for(item)))

    def test_access_report_and_bilingual_notes_required(self):
        item=copy.deepcopy(next(x for x in self.cases if x.get('access')))
        item['access']['page_note']['zh-CN']=''
        self.assertTrue(any('bilingual note' in x for x in self.errors_for(item)))
        item['access']['report_path']='docs/not-a-report.md'
        self.assertTrue(any('file does not exist' in x for x in self.errors_for(item)))

    def test_source_linked_mp4_is_video_not_gif(self):
        item=copy.deepcopy(next(x for x in self.cases if any(m['kind']=='video' for m in x['media'])))
        self.assertEqual(self.errors_for(item), [])
        media=next(m for m in item['media'] if m['kind']=='video')
        media['kind']='gif'
        self.assertTrue(any('MP4 sources' in x for x in self.errors_for(item)))

    def test_same_day_latest_uses_collection_order(self):
        cases=copy.deepcopy(self.cases[:2])
        cases[0]['id']='zz-older';cases[1]['id']='aa-newer'
        cases[0]['added_at']=cases[1]['added_at']='2026-11-05'
        with patch('homepage.read_cases',return_value=cases):
            text=render_readme(self.config,self.prompts,'en')
        latest=text.split('<a id="latest"></a>',1)[1].split('<a id="all-cases"></a>',1)[0]
        self.assertLess(latest.index('cases/aa-newer/'),latest.index('cases/zz-older/'))

    def media_item(self):
        return copy.deepcopy(next(x for x in self.cases if x['media']))

    def test_link_only_media_cannot_be_embedded(self):
        item=self.media_item();item['media'][0]['path']='assets/header.svg';item['media'][0]['rights']['status']='link-only'
        self.assertTrue(self.errors_for(item))

    def test_remote_embedded_media_rejected(self):
        item=self.media_item();m=item['media'][0];m['path']='https://example.com/image.png';m['rights']['status']='licensed';m['rights']['evidence_url']='https://example.com/license'
        self.assertTrue(self.errors_for(item))

    def test_local_media_requires_evidence(self):
        item=self.media_item();m=item['media'][0];m['path']='assets/header.svg';m['rights']['status']='licensed';m['rights']['evidence_url']=None
        self.assertTrue(any('evidence' in x for x in self.errors_for(item)))

    def test_local_evidence_route_is_relative_to_case_page(self):
        item=self.media_item();item['media'][0]['rights']['evidence_url']='docs/ATTRIBUTION.md'
        self.assertIn('(../../docs/ATTRIBUTION.md)', render_detail(item, 'en'))

    def test_free_text_cannot_embed_remote_images(self):
        item=self.media_item()
        bad='![remote](https://example.com/unlicensed.png) <img src="https://example.com/x.png" />'
        item['notes']['en']=bad
        item['model']['evidence']['en']=bad
        item['media'][0]['rights']['note']['en']=bad
        text=render_detail(item,'en')
        self.assertNotIn('![remote](',text)
        self.assertNotRegex(text, r'<img\b[^>]*src=[\"\'](?:https?:|//)')
        self.assertIn('&lt;img src=',text)

    def test_local_path_traversal_is_rejected(self):
        item=self.media_item();m=item['media'][0];m['path']=f"assets/examples/{item['id']}/../../header.svg";m['rights']['status']='licensed';m['rights']['evidence_url']='https://example.com/license'
        self.assertTrue(any('traversal' in x for x in self.errors_for(item)))


if __name__ == '__main__':
    unittest.main()

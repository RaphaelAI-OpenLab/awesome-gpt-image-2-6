"""Shared data and URL helpers. Python 3.10+, standard library only."""

from __future__ import annotations

import html
import json
import re
from pathlib import Path
from i18n import LANGUAGES, translated_source, ui
from urllib.parse import parse_qsl, urlencode, urlsplit, urlunsplit

ROOT = Path(__file__).resolve().parents[1]
GENERATED_MARKER = "<!-- Generated by scripts/build_readme.py. Edit source data, locale catalogs and generator scripts. -->"


def read_json(relative_path: str):
    return json.loads((ROOT / relative_path).read_text(encoding="utf-8"))


def load_data():
    return read_json("site.config.json"), read_json("content/prompts.json")


def localized(value, language: str) -> str:
    if isinstance(value, str):
        return value
    if not isinstance(value, dict):
        return ""
    return str(value.get(language) or translated_source(value.get("en") or "", language))


def published(prompts: list[dict]) -> list[dict]:
    return sorted(
        (item for item in prompts if item.get("status") == "published"),
        key=lambda item: (item.get("added_at") or "", item.get("id") or ""),
        reverse=True,
    )


def repo_url(config: dict) -> str | None:
    project = config["project"]
    owner = project.get("repository_owner", "").strip()
    if not owner:
        return None
    return f"https://github.com/{owner}/{project['repository_slug']}"


def is_brand_url(url: str, config: dict) -> bool:
    host = (urlsplit(url).hostname or "").lower()
    brand_host = (urlsplit(config["brand"]["home_url"]).hostname or "").lower()
    return bool(brand_host) and (host == brand_host or host.endswith("." + brand_host))


def tracked_url(url: str, placement: str, language: str, config: dict) -> str:
    """Preserve functional query parameters; replace only our UTM fields.

    Source attribution and GitHub links never receive campaign parameters.
    """
    if not is_brand_url(url, config):
        return url
    parts = urlsplit(url)
    tracking = dict(config["tracking"])
    tracking["utm_content"] = placement
    tracking["utm_term"] = language
    query = [(key, value) for key, value in parse_qsl(parts.query, keep_blank_values=True) if key not in tracking]
    query.extend(tracking.items())
    return urlunsplit((parts.scheme, parts.netloc, parts.path, urlencode(query), parts.fragment))


def md_text(value) -> str:
    value = str(value).replace("\n", " ").strip()
    for old, new in (("\\", "\\\\"), ("[", "\\["), ("]", "\\]"), ("|", "\\|"), ("<", "&lt;"), (">", "&gt;")):
        value = value.replace(old, new)
    return value


def md_url(url: str) -> str:
    return url.replace(" ", "%20").replace("(", "%28").replace(")", "%29")


def md_link(label: str, url: str) -> str:
    return f"[{md_text(label)}]({md_url(url)})"


def render_gallery_cta(config: dict, language: str, case_id: str) -> str:
    """案例底部统一打开提示词图库，并记录案例与语言归因。"""
    title = '👉 ' + ui('Try now →', '立即尝试 →', language)
    url = tracked_url(config['brand']['gallery_url'], f'case_gallery_{case_id}', language, config)
    return '**' + md_link(title, url) + '**'


def code_block(value: str) -> str:
    max_run = max((len(match.group()) for match in re.finditer(r"`+", value)), default=0)
    fence = "`" * max(3, max_run + 1)
    return f"{fence}text\n{value.rstrip()}\n{fence}"


def image_path(path: str, prefix: str = "") -> str:
    return path if urlsplit(path).scheme else prefix + path


def html_attr(value) -> str:
    return html.escape(str(value), quote=True)

"""Live repository badges alongside original local language/navigation SVGs."""
import html
import unicodedata
from pathlib import Path
from urllib.parse import quote, urlencode
from i18n import LANGUAGES, DETAIL_LANGUAGES, LANGUAGE_NAMES, filename, ui

ROOT = Path(__file__).resolve().parents[1]
BADGES = {
    'license': ('CODE · MIT', '#5b21b6', 'LICENSE'),
    'sources': ('SOURCE · TERMS', '#92400e', 'docs/ATTRIBUTION.md'),
    'contribute': ('PRs · WELCOME', '#166534', 'CONTRIBUTING.md'),
    'ci': ('CI · VIEW RUNS', '#075985', None),
    'star': ('GITHUB · STAR', '#9d174d', None),
}


def text_width(text, size=12):
    units = sum(0 if unicodedata.combining(c) else 1.75 if unicodedata.east_asian_width(c) in 'WF' else .66 for c in text)
    return round(units * size)


def pill(text, color, *, current=False, solid=False, title=None):
    width = max(90, text_width(text) + (49 if current else 32))
    label, description = html.escape(text), html.escape(title or text)
    background, foreground, border = (color, '#ffffff', color) if (current or solid) else ('#f8fafc', color, '#cbd5e1')
    check = f'<path d="M{width-27} 16l4 4 8-9" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"/>' if current else ''
    return f'''<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="34" viewBox="0 0 {width} 34" role="img" aria-label="{description}">
  <!-- Generated by scripts/build_readme.py; original decorative artwork. -->
  <title>{description}</title><rect x=".5" y=".5" width="{width-1}" height="33" rx="8" fill="{background}" stroke="{border}"/>
  <g color="{foreground}"><text x="16" y="22" fill="currentColor" font-family="Arial, 'Noto Sans', sans-serif" font-size="12" font-weight="600">{label}</text>{check}</g>
</svg>
'''


def language_nav(language, *, prefix='', detail=False):
    codes = DETAIL_LANGUAGES if detail else LANGUAGES
    links = []
    for code in codes:
        active = code == language
        state = 'Current language' if active else 'View translation'
        alt = ui(state, language=language) + ': ' + LANGUAGE_NAMES[code]
        asset = f'{prefix}assets/badges/language-{code}' + ('-current' if active else '') + '.svg'
        links.append(f'<a href="{filename(code)}"><img src="{asset}" alt="{html.escape(alt, quote=True)}" height="34" /></a>')
    # Four links per row avoid an unreadable sixteen-wide strip on mobile.
    return '\n'.join(' '.join(links[start:start+4]) + ('<br />' if start+4<len(links) else '') for start in range(0,len(links),4))


def repo_badges(config, language):
    project = config['project']
    slug = f"{project['repository_owner']}/{project['repository_slug']}"
    repo = f'https://github.com/{slug}'
    workflow = repo + '/actions/workflows/validate.yml'
    branch_query = urlencode({'branch': project['default_branch']})
    badges = [
        ('Awesome', 'https://awesome.re/badge.svg', 'https://github.com/sindresorhus/awesome'),
        (ui('Star on GitHub', language=language), f'https://img.shields.io/github/stars/{quote(slug, safe="/")}?style=social', repo),
        (ui('Code & original docs', language=language) + ': MIT', 'https://img.shields.io/badge/License-MIT-lightgrey.svg', 'LICENSE'),
        (ui('Validation CI', language=language), workflow + '/badge.svg?' + branch_query, workflow),
        (ui('Contributions welcome', language=language), 'https://img.shields.io/badge/PRs-welcome-brightgreen.svg', 'CONTRIBUTING.md'),
    ]
    return '\n'.join(f'[![{label}]({image})]({target})' for label, image, target in badges)


def placeholder(language):
    title = ui('Images not yet archived', language=language)
    note = ui('Placeholder, not model output', language=language)
    size = min(24, round(640 / max(1, text_width(title, 1)), 1))
    return f'''<svg xmlns="http://www.w3.org/2000/svg" width="720" height="300" viewBox="0 0 720 300" role="img" aria-label="{html.escape(title, quote=True)}">
  <!-- Generated by scripts/build_readme.py; not a model output. -->
  <title>{html.escape(title)}</title><desc>{html.escape(note)}</desc>
  <rect width="720" height="300" rx="20" fill="#f8fafc"/>
  <rect x="24" y="24" width="672" height="252" rx="12" fill="none" stroke="#cbd5e1" stroke-dasharray="7 7"/>
  <text x="360" y="143" text-anchor="middle" font-family="Arial, 'Noto Sans', sans-serif" font-size="{size}" font-weight="600" fill="#334155">{html.escape(title)}</text>
  <text x="360" y="182" text-anchor="middle" font-family="Arial, 'Noto Sans', sans-serif" font-size="16" fill="#64748b">{html.escape(note)}</text>
</svg>
'''


def asset_outputs():
    result = {}
    for language in LANGUAGES:
        label = LANGUAGE_NAMES[language]
        result[ROOT / f'assets/badges/language-{language}.svg'] = pill(label, '#475569', title=ui('View translation', language=language) + ': ' + label)
        result[ROOT / f'assets/badges/language-{language}-current.svg'] = pill(label, '#4338ca', current=True, title=ui('Current language', language=language) + ': ' + label)
        for key, (text, color, _) in BADGES.items():
            result[ROOT / f'assets/badges/{key}-{language}.svg'] = pill(ui(text, language=language), color, solid=True)
        result[ROOT / f'assets/media-placeholder-{language}.svg'] = placeholder(language)
    return result
